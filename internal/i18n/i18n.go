func Normalize(lang string) string {
	switch strings.ToLower(strings.TrimSpace(lang)) {
	case "en":
		return "en"
	case "be", "by":
		return "be"
	default:
		return "ru"
	}
}

func T(lang, key string) string {
	lang = Normalize(lang)
	if value, ok := dictionary[lang][key]; ok {
		return value
	}
	if value, ok := dictionary["ru"][key]; ok {
		return value
	}
	return key
}
